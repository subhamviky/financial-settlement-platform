-- Settlement service schema (Flyway). Works on PostgreSQL and on H2 in PostgreSQL mode.

create table account (
    id          varchar(40)    primary key,
    tenant_id   varchar(40)    not null,
    currency    varchar(3)     not null,
    balance     numeric(19, 2) not null,
    version     bigint         not null default 0
);

create table settlement (
    id             uuid           primary key,
    tenant_id      varchar(40)    not null,
    payer_account  varchar(40)    not null,
    payee_account  varchar(40)    not null,
    amount         numeric(19, 2) not null,
    currency       varchar(3)     not null,
    status         varchar(20)    not null,
    failure_reason varchar(500),
    version        bigint         not null default 0,
    created_at     timestamp with time zone not null,
    updated_at     timestamp with time zone not null
);

create table ledger_entry (
    id            bigint generated by default as identity primary key,
    settlement_id uuid           not null,
    account_id    varchar(40)    not null,
    direction     varchar(6)     not null,
    amount        numeric(19, 2) not null,
    posting_type  varchar(12)    not null,
    created_at    timestamp with time zone not null
);
create index ledger_entry_settlement on ledger_entry (settlement_id);

create table outbox_event (
    id           bigint generated by default as identity primary key,
    event_id     uuid          not null unique,
    tenant_id    varchar(40)   not null,
    aggregate_id uuid          not null,
    event_type   varchar(60)   not null,
    payload      varchar(4000) not null,
    created_at   timestamp with time zone not null,
    published_at timestamp with time zone
);
create index outbox_event_unpublished on outbox_event (published_at, id);

create table idempotency_record (
    tenant_id       varchar(40)   not null,
    idempotency_key varchar(100)  not null,
    fingerprint     varchar(64)   not null,
    status          varchar(12)   not null,
    http_status     integer,
    response_body   varchar(4000),
    created_at      timestamp with time zone not null,
    updated_at      timestamp with time zone not null,
    primary key (tenant_id, idempotency_key)
);

